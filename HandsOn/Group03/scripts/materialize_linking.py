"""Execute the submitted RML mappings with Morph-KGC; run from any directory."""
import argparse
import gc
import os
from pathlib import Path
import time

import morph_kgc

ROOT=Path(__file__).resolve().parents[1]
DATASETS=['estaciones_acusticas','terrazas_hosteleria','contaminacion_acustica']


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dataset',choices=DATASETS)
    args=parser.parse_args()
    os.chdir(ROOT)
    for name in [args.dataset] if args.dataset else DATASETS:
        config=f'''[CONFIGURATION]
number_of_processes=1
logging_level=WARNING
[DataSource]
mappings=mappings/{name}-with-links.rml
'''
        start=time.monotonic()
        graph=morph_kgc.materialize(config)
        for prefix,uri in {'mn':'https://madridnoise.linkeddata.es/ontology#',
                           'station':'https://madridnoise.linkeddata.es/resource/station/',
                           'observation':'https://madridnoise.linkeddata.es/resource/observation/',
                           'terrace':'https://madridnoise.linkeddata.es/resource/terrace/',
                           'district':'https://madridnoise.linkeddata.es/resource/district/',
                           'neighbourhood':'https://madridnoise.linkeddata.es/resource/neighbourhood/',
                           'period':'https://madridnoise.linkeddata.es/resource/period/',
                           'dataset':'https://madridnoise.linkeddata.es/dataset/'}.items():
            graph.bind(prefix,uri)
        output=ROOT/'rdf'/f'{name}-with-links.ttl'
        temporary=output.with_suffix('.ttl.tmp')
        graph.serialize(destination=temporary,format='turtle',encoding='utf-8')
        temporary.replace(output)
        print(f'{name}: {len(graph):,} triples generated by Morph-KGC in {time.monotonic()-start:.1f}s',flush=True)
        del graph
        gc.collect()


if __name__=='__main__':
    main()
